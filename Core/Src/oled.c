void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
    uint8_t i;
    uint8_t index;

    if (y > 7) return;                    /* 页号越界保护 */
    if (x > (OLED_WIDTH - 6)) return;      /* 横向越界保护 */

    /* 只支持可显示 ASCII 字符，其它字符用空格代替 */
    if (ch < ' ' || ch > '~')
        ch = ' ';

    index = (uint8_t)(ch - ' ');          /* 字库下标 */

    OLED_WriteCmd(0xB0 + y);              /* 选中页       */
    OLED_WriteCmd(0x00 | (x & 0x0F));     /* 列低 4 位    */
    OLED_WriteCmd(0x10 | (x >> 4));       /* 列高 4 位    */

    for (i = 0; i < 6; i++)
    {
        OLED_WriteData(F6x8[index][i]);   /* 逐列写 6 个字节 */
    }
}

void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
    while (*str != '\0')
    {
        if (x > (OLED_WIDTH - 6))         /* 一行放不下就停止，防止越界 */
            break;

        OLED_ShowChar(x, y, *str);
        x += 6;
        str++;
    }
}

void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    uint8_t i;

    if (len == 0) return;

    /* 从最低位开始，依次往左放 */
    for (i = 0; i < len; i++)
    {
        OLED_ShowChar(x + (len - 1 - i) * 6, y, (char)('0' + num % 10));
        num /= 10;
    }
}
